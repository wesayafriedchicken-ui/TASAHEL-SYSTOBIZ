function getSmartUpdateItemFallback(itemType: string, currentText: string, promptInstruction: string) {
  let result = currentText;
  const instructionLower = promptInstruction.toLowerCase();
  const isAr = /[\u0600-\u06FF]/.test(currentText);

  if (instructionLower.includes("اختصار") || instructionLower.includes("قصير") || instructionLower.includes("short") || instructionLower.includes("brief")) {
    const sentences = currentText.split(/[.،]/);
    if (sentences.length > 1) {
      result = sentences[0].trim() + " " + (sentences[1] ? sentences[1].trim() : "") + ".";
    }
  } else if (instructionLower.includes("طويل") || instructionLower.includes("توسيع") || instructionLower.includes("expand") || instructionLower.includes("detailed") || instructionLower.includes("تفصيل")) {
    result = currentText + " " + (isAr 
      ? "بالإضافة إلى تفعيل شروط الرقابة والالتزام التام بمتطلبات الجودة لضمان الكفاءة القصوى والنمو المستدام." 
      : "ensuring comprehensive quality checks, regulatory compliance, and maximum operational efficiency standards.");
  } else {
    if (isAr) {
      result = currentText.replace(/(ممتاز|رائع|متميز)/g, "متكامل واحترافي");
    } else {
      result = currentText.replace(/(good|great|nice)/gi, "flawless and highly optimized");
    }
  }
  return result;
}

