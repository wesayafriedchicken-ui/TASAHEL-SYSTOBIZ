function getSmartGenerateFallback(seedInput: string, answers: any[]) {
  const isAr = /[\u0600-\u06FF]/.test(seedInput);
  
  // Detect Industry
  let industry: 'tourism' | 'kitchen' | 'laundry' | 'general' = 'general';
  if (/سياح|رحل|سفر|طيران|استشفا/.test(seedInput)) {
    industry = 'tourism';
  } else if (/مطبخ|جرانيت|طبيعي|أواني|متجر|أدوات/.test(seedInput)) {
    industry = 'kitchen';
  } else if (/غسيل|لاندري|ملابس|اشتراك/.test(seedInput)) {
    industry = 'laundry';
  }

  if (isAr) {
    if (industry === 'tourism') return getArabicTourismPayload(seedInput);
    if (industry === 'kitchen') return getArabicKitchenPayload(seedInput);
    if (industry === 'laundry') return getArabicLaundryPayload(seedInput);
    return getArabicGeneralPayload(seedInput);
  } else {
    return getEnglishGeneralPayload(seedInput);
  }
}

