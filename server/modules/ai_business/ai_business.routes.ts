  router.post("/update-item", async (req, res) => {
    try {
      const { itemType, itemId, currentText, promptInstruction } = req.body;
      if (!currentText || !promptInstruction) {
        return res.status(400).json({ error: "Required fields (currentText, promptInstruction) missing." });
      }

      let updatedText = currentText;
      const ai = getAiClient();

      if (ai) {
        try {
          const prompt = `You are a high-speed business systems automation agent.
The user wants to refine a specific textual element within their database.

Element Category: "${itemType}"
Current Contents:
"${currentText}"

User's refinement/editing instruction:
"${promptInstruction}"

Apply the instructions completely. Preserve the language (Arabic or English) and tone context.
Return ONLY the direct, fully polished, complete replacement text. Do NOT add preamble, quotation marks, or explanations.`;

          const response = await ai.models.generateContent({
            model: "gemini-3.5-flash",
            contents: prompt,
          });

          updatedText = response.text?.trim() || currentText;
        } catch (apiErr: any) {
          const isExpired = apiErr?.message?.includes("expired") || apiErr?.message?.includes("API key");
          console.log(`ℹ️ [Gemini Edit Info] ${isExpired ? "API Key is expired/inactive. Using local interactive polish rules." : "API call finished: processing edit fallback"}`);
          updatedText = getSmartUpdateItemFallback(itemType, currentText, promptInstruction);
        }
      } else {
        updatedText = getSmartUpdateItemFallback(itemType, currentText, promptInstruction);
      }

      // Update the database depending on the element type
      if (itemId && itemId !== "local") {
        try {
          if (itemType === "sop_description" || itemType === "sop_objective") {
             const fieldName = itemType === "sop_objective" ? "objective" : "scope";
             await pool.query(`UPDATE sops SET ${fieldName} = $1 WHERE id = $2`, [updatedText, itemId]);
          } else if (itemType === "sop_step") {
             await pool.query("UPDATE sop_steps SET step_description = $1 WHERE id = $2", [updatedText, itemId]);
          } else if (itemType === "task") {
             await pool.query("UPDATE tasks SET description = $1 WHERE id = $2", [updatedText, itemId]);
          } else if (itemType === "risk") {
             await pool.query("UPDATE risks SET description = $1 WHERE id = $2", [updatedText, itemId]);
          } else if (itemType === "marketing_content") {
             await pool.query("UPDATE marketing_content SET content_text = $1 WHERE id = $2", [updatedText, itemId]);
          } else if (itemType === "kb_article") {
             await pool.query("UPDATE knowledge_articles SET content = $1 WHERE id = $2", [updatedText, itemId]);
          }
        } catch (dbErr) {
          console.warn("Element was visual-only or DB update skipped: ", dbErr);
        }
      }

      res.json({ success: true, updatedText });
    } catch (err) {
      console.error("Error in AI real-time modification:", err);
      res.status(500).json({ error: "Failed to modify element with AI advice." });
    }
  });

